[CmdletBinding()]
param(
    [string]$RuntimeRoot = (Join-Path $PSScriptRoot '..\assets\runtime\production\title'),
    [string]$IncludeOutput = (Join-Path $PSScriptRoot '..\src\generated\title_assets.inc')
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

[byte[]]$background = [IO.File]::ReadAllBytes((Join-Path $RuntimeRoot 'ACRUX_TITLE_BG_320x180.raw'))
if ($background.Length -ne 57600) { throw "Title background must be exactly 57600 bytes, got $($background.Length)." }

[byte[]]$palette = [IO.File]::ReadAllBytes((Join-Path $RuntimeRoot 'ACRUX_TITLE_BG_palette24.rgb'))
if ($palette.Length -ne 72) { throw "Title palette must be exactly 72 bytes, got $($palette.Length)." }

function Byte-Array([string]$Name, [byte[]]$Data) {
    $builder = [Text.StringBuilder]::new()
    [void]$builder.Append("static constexpr std::uint8_t $Name[$($Data.Length)] = {`n")
    for($offset=0;$offset -lt $Data.Length;$offset+=32){
        $count=[Math]::Min(32,$Data.Length-$offset)
        $line=for($i=0;$i -lt $count;$i++){'0x{0:X2}' -f $Data[$offset+$i]}
        [void]$builder.Append('    '+($line -join ', ')+",`n")
    }
    [void]$builder.Append("};`n`n")
    return $builder.ToString()
}

$builder=[Text.StringBuilder]::new()
[void]$builder.Append("// Generated by scripts/embed-title-assets.ps1. Do not edit by hand.`n")
[void]$builder.Append((Byte-Array 'kTitleBackgroundPixels' $background))
[void]$builder.Append((Byte-Array 'kTitleBackgroundPaletteRgb' $palette))

$parent=Split-Path -Parent ([IO.Path]::GetFullPath($IncludeOutput))
if(-not(Test-Path $parent)){New-Item -ItemType Directory -Path $parent | Out-Null}
[IO.File]::WriteAllText([IO.Path]::GetFullPath($IncludeOutput),$builder.ToString(),[Text.UTF8Encoding]::new($false))
Write-Host "PASS title assets: $($background.Length + $palette.Length) bytes"
