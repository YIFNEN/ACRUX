[CmdletBinding()]
param(
    [string]$RuntimeRoot = (Join-Path $PSScriptRoot '..\assets\runtime\production\cutscenes'),
    [string]$IncludeOutput = (Join-Path $PSScriptRoot '..\src\generated\cutscene_assets.inc')
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$scenes = @(
    @('ACRUX_01_Sleep_480x270_256c_indexed8.raw', 'ACRUX_01_Sleep_256c_palette.rgb'),
    @('ACRUX_02_SolarCharge_480x270_256c_indexed8.raw', 'ACRUX_02_SolarCharge_256c_palette.rgb'),
    @('ACRUX_03_Dusk_480x270_256c_indexed8.raw', 'ACRUX_03_Dusk_256c_palette.rgb'),
    @('ACRUX_04_Ending_480x270_256c_indexed8.raw', 'ACRUX_04_Ending_256c_palette.rgb')
)

$bytes = [Collections.Generic.List[byte]]::new()
$palettes = [Collections.Generic.List[byte]]::new()
$offsets = [Collections.Generic.List[string]]::new()
foreach ($scene in $scenes) {
    $path = Join-Path $RuntimeRoot $scene[0]
    [byte[]]$raw = [IO.File]::ReadAllBytes($path)
    if ($raw.Length -ne 129600) { throw "$($scene[0]) must be exactly 129600 bytes, got $($raw.Length)." }
    $palettePath = Join-Path $RuntimeRoot $scene[1]
    [byte[]]$palette = [IO.File]::ReadAllBytes($palettePath)
    if ($palette.Length -ne 768) { throw "$($scene[1]) must be exactly 768 bytes, got $($palette.Length)." }
    $offsets.Add("    $($bytes.Count)u, // $($scene[0])")
    $bytes.AddRange($raw)
    $palettes.AddRange($palette)
}

function Byte-Array([string]$Name, [byte[]]$Data) {
    $builder = [Text.StringBuilder]::new()
    [void]$builder.Append("static constexpr std::uint8_t $Name[$($Data.Length)] = {`n")
    for($offset=0;$offset -lt $Data.Length;$offset+=32){
        $count=[Math]::Min(32,$Data.Length-$offset)
        $line=for($i=0;$i -lt $count;$i++){'0x{0:X2}' -f $Data[$offset+$i]}
        [void]$builder.Append('    '+($line -join ', ')+",`n")
    }
    [void]$builder.Append("};`n`n")
    return $builder.ToString()
}

$builder=[Text.StringBuilder]::new()
[void]$builder.Append("// Generated by scripts/embed-cutscene-assets.ps1. Do not edit by hand.`n")
[void]$builder.Append((Byte-Array 'kCutsceneBytes' $bytes.ToArray()))
[void]$builder.Append((Byte-Array 'kCutscenePaletteRgb' $palettes.ToArray()))
[void]$builder.Append("static constexpr std::uint32_t kCutsceneOffsets[$($scenes.Count)] = {`n")
[void]$builder.Append(($offsets -join "`n"))
[void]$builder.Append("`n};`n")

$parent=Split-Path -Parent ([IO.Path]::GetFullPath($IncludeOutput))
if(-not(Test-Path $parent)){New-Item -ItemType Directory -Path $parent | Out-Null}
[IO.File]::WriteAllText([IO.Path]::GetFullPath($IncludeOutput),$builder.ToString(),[Text.UTF8Encoding]::new($false))
Write-Host "PASS cutscene assets: $($scenes.Count) scenes, $($bytes.Count + $palettes.Count) bytes"
